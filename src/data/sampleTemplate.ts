function staticReferencePage(
  id: string,
  name: string,
  assetName: string,
  dynamicPeriod: boolean,
): ReportPage {
  return {
    id,
    name,
    width: 816,
    height: 1056,
    background: "#ffffff",
    elements: [
      image(
        `${id}-artwork`,
        `${name} Reference Artwork`,
        0,
        0,
        816,
        1056,
        `/report-assets/static-pages/${assetName}.png`,
        "stretch",
      ),
      ...(dynamicPeriod
        ? [
            {
              ...text(
                `${id}-period`,
                "Quarter",
                598,
                21,
                184,
                43,
                "Q2 2026",
                35,
                white,
                800,
                "right",
              ),
              binding: { path: "reportDisplay.period" },
            },
          ]
        : []),
    ],
  };
}

