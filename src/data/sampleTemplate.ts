function propertySection(
  id: string,
  title: string,
  y: number,
  items: PropertyHighlight[],
): ReportElement[] {
  const result: ReportElement[] = [
    shape(`${id}-bar`, `${title} Bar`, 32, y, 752, 27, crimson, 8),
    text(
      `${id}-section-title`,
      title,
      32,
      y + 2,
      752,
      23,
      title,
      17,
      white,
      800,
      "center",
    ),
  ];
  items.forEach((item, index) => {
    const x = 32 + index * 257,
      width = index === 2 ? 238 : 239;
    result.push(
      image(
        `${id}-image-${index}`,
        item.address,
        x,
        y + 27,
        width,
        137,
        item.image,
        "cover",
      ),
    );
    result.push(
      shape(
        `${id}-caption-${index}`,
        "Caption",
        x,
        y + 164,
        width,
        47,
        navy,
        index === 0 ? 8 : 0,
      ),
    );
    result.push(
      text(
        `${id}-text-${index}`,
        item.address,
        x + 7,
        y + 170,
        width - 14,
        17,
        item.address,
        8.1,
        white,
        700,
        "center",
      ),
    );
    result.push(
      text(
        `${id}-detail-${index}`,
        "Property Details",
        x + 7,
        y + 188,
        width - 14,
        18,
        `${item.sizeSf.toLocaleString("en-US")} SF - ${item.type}${item.sponsor ? ` - ${item.sponsor}` : ""}`,
        7.5,
        white,
        600,
        "center",
      ),
    );
  });
  return result;
}

